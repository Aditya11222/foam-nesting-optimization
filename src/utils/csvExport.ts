import type { OptimizationResult } from '../types';
import { DEFAULT_COST_ASSUMPTIONS, type CostAssumptions } from '../tokens';

export function exportJobCSV(
  currentResult: OptimizationResult,
  comparisonResults: OptimizationResult[] = [],
  costAssumptions: CostAssumptions = DEFAULT_COST_ASSUMPTIONS
): void {
  const isoNow = new Date().toISOString();
  const gradeCostPerCuFt =
    costAssumptions.gradeCostPerCuFt[currentResult.grade] ?? 4.85;

  const grossCuFt = currentResult.total_gross_volume / 1728;
  const partsCuFt = currentResult.total_parts_volume / 1728;
  const remnantCuFt = currentResult.total_remnant_volume / 1728;
  const scrapCuFt = currentResult.total_unrecoverable_scrap_volume / 1728;
  const trimCuFt =
    Math.max(0, currentResult.total_gross_volume - currentResult.total_usable_volume) /
    1728;
  const kerfCuFt = currentResult.total_kerf_volume / 1728;

  const rawMaterialCost = grossCuFt * gradeCostPerCuFt;
  const sawHours =
    (currentResult.total_cuts_count * costAssumptions.secondsPerCut) / 3600;
  const sawLaborCost = sawHours * costAssumptions.sawHourlyRate;
  const remnantCredit =
    remnantCuFt * gradeCostPerCuFt * (costAssumptions.remnantReuseCreditPct / 100);
  const netEstimatedCost = Math.max(0, rawMaterialCost + sawLaborCost - remnantCredit);

  // Baseline assumptions (estimated, demo assumptions)
  const baselineYieldRatio = costAssumptions.baselineYieldPct / 100;
  const baselineGrossCuFt =
    baselineYieldRatio > 0 ? partsCuFt / baselineYieldRatio : grossCuFt * 1.18;
  const baselineScrapCuFt = Math.max(0, baselineGrossCuFt - partsCuFt);
  const baselineCost =
    baselineGrossCuFt * gradeCostPerCuFt + sawLaborCost * 1.15;
  const wasteReducedPct =
    baselineScrapCuFt > 0
      ? ((baselineScrapCuFt - scrapCuFt) / baselineScrapCuFt) * 100
      : 0;

  const lines: string[] = [];

  // 1. SUMMARY
  lines.push('# 1. SUMMARY (heuristic solution — cost & baseline figures are estimated, demo assumptions)');
  lines.push('Metric,Value,Unit,Notes');
  lines.push(`Export Timestamp (ISO),"${isoNow}",ISO-8601,Generated by Tatras NestPro`);
  lines.push(`Job ID,"${currentResult.job_id}",id,Batch identifier`);
  lines.push(`Foam Grade,"${currentResult.grade}",grade,Polyurethane bun specification`);
  lines.push(`Selected Heuristic,"${currentResult.algorithm_name}",algorithm,Heuristic solution (not proven optimal)`);
  lines.push(`Machine Profile,"${currentResult.machine.name}",station,Cut type: ${currentResult.machine.cut_type}`);
  lines.push(`Net Usable Yield,${currentResult.net_utilization_pct.toFixed(2)},%,Parts volume / usable interior volume`);
  lines.push(`Gross Bun Yield,${currentResult.gross_utilization_pct.toFixed(2)},%,Parts volume / gross nominal volume`);
  lines.push(`Blocks Used,${currentResult.blocks_used_count},blocks,Total foam buns consumed`);
  lines.push(`Parts Placed,${currentResult.total_parts_placed} / ${currentResult.total_parts_demanded},pieces,Total pieces nested`);
  lines.push(`Total Cuts,${currentResult.total_cuts_count},cuts,Saw passes across all blocks`);
  lines.push(`Estimated Saw Time,${currentResult.estimated_saw_time_minutes.toFixed(2)},minutes,Estimated demo assumption`);
  lines.push(`Gross Bun Volume,${grossCuFt.toFixed(3)},cu ft,${Math.round(currentResult.total_gross_volume)} cu in`);
  lines.push(`Placed Parts Volume,${partsCuFt.toFixed(3)},cu ft,${Math.round(currentResult.total_parts_volume)} cu in`);
  lines.push(`Retained Remnants Volume,${remnantCuFt.toFixed(3)},cu ft,${Math.round(currentResult.total_remnant_volume)} cu in`);
  lines.push(`Skin Trim Volume,${trimCuFt.toFixed(3)},cu ft,${Math.round(trimCuFt * 1728)} cu in`);
  lines.push(`Blade Kerf Volume,${kerfCuFt.toFixed(3)},cu ft,${Math.round(currentResult.total_kerf_volume)} cu in`);
  lines.push(`Unrecoverable Scrap Volume,${scrapCuFt.toFixed(3)},cu ft,${Math.round(currentResult.total_unrecoverable_scrap_volume)} cu in`);
  lines.push(`Estimated Net Total Cost,${netEstimatedCost.toFixed(2)},USD,Estimated demo assumption`);
  lines.push(`Waste Reduced vs Baseline,${wasteReducedPct.toFixed(1)},%,Estimated demo assumption`);
  lines.push('');

  // 2. PARTS_PLACED
  lines.push('# 2. PARTS_PLACED');
  lines.push(
    'Block #,Stock ID,Part ID,Part SKU,Part Name,Foam Grade,X Origin (in),Y Origin (in),Z Origin (in),Length (in),Width (in),Height (in),Volume (cu in),Volume (cu ft),Orientation Used'
  );
  for (const b of currentResult.blocks) {
    for (const p of b.placed_parts) {
      const volIn = p.length * p.width * p.height;
      const orientStr = p.orientation_used.join('x');
      lines.push(
        `${b.block_index},"${b.stock_id}","${p.part_id}","${p.sku}","${p.name}","${p.grade}",${p.x},${p.y},${p.z},${p.length},${p.width},${p.height},${volIn.toFixed(1)},${(volIn / 1728).toFixed(4)},"${orientStr}"`
      );
    }
  }
  lines.push('');

  // 3. CUT_SEQUENCE
  lines.push('# 3. CUT_SEQUENCE');
  lines.push(
    'Block #,Step #,Stage,Cut Type,Axis,Fence Position (in),Fence Fractional (in),Blade Kerf (in),Target Length (in),Target Width (in),Target Height (in),Keep Offcut Flag,Operator Instruction (EN)'
  );
  for (const b of currentResult.blocks) {
    for (const c of b.cuts) {
      const keepOffcut = c.remnant_prompt_en ? 'KEEP_REMNANT' : 'STANDARD';
      lines.push(
        `${b.block_index},${c.step_number},${c.stage},"${c.cut_type}",${c.axis},${c.position_in},"${c.position_display}",${c.kerf_in},${c.target_piece_dims[0]},${c.target_piece_dims[1]},${c.target_piece_dims[2]},${keepOffcut},"${c.produces_description_en.replace(/"/g, '""')}"`
      );
    }
  }
  lines.push('');

  // 4. REMNANTS
  lines.push('# 4. REMNANTS');
  lines.push(
    'Block #,Remnant Code,Foam Grade,Length (in),Width (in),Height (in),Volume (cu in),Volume (cu ft),Usability Score (0-1),Storage Rack Location'
  );
  for (const b of currentResult.blocks) {
    for (const r of b.usable_remnants) {
      lines.push(
        `${b.block_index},"${r.code}","${r.grade}",${r.length},${r.width},${r.height},${Math.round(r.volume)},${(r.volume / 1728).toFixed(3)},${r.usability_score},"${r.storage_location}"`
      );
    }
  }
  lines.push('');

  // 5. ALGORITHM_COMPARISON
  lines.push('# 5. ALGORITHM_COMPARISON');
  lines.push(
    'Algorithm ID,Algorithm Name,Net Usable Yield (%),Gross Yield (%),Scrap Volume (cu ft),Blocks Used (count),Total Cuts (count),Saw Time (min),Runtime (ms),Validation Status,Solver Status,Best in Comparison'
  );
  const algoRows =
    comparisonResults.length > 0 ? comparisonResults : [currentResult];
  for (const r of algoRows) {
    lines.push(
      `"${r.algorithm_id}","${r.algorithm_name}",${r.net_utilization_pct.toFixed(2)},${r.gross_utilization_pct.toFixed(2)},${(r.total_unrecoverable_scrap_volume / 1728).toFixed(2)},${r.blocks_used_count},${r.total_cuts_count},${r.estimated_saw_time_minutes.toFixed(1)},${r.runtime_ms},${r.validation?.is_valid ? 'VALID' : 'CHECK'},"${r.solver_status || 'HEURISTIC'}",${r.is_best ? 'BEST_TESTED_HEURISTIC' : 'NO'}`
    );
  }
  lines.push('');

  // 6. BASELINE_VS_OPTIMIZED
  lines.push('# 6. BASELINE_VS_OPTIMIZED (estimated, demo assumptions)');
  lines.push('Metric,Shop Baseline (Estimated),Optimized Heuristic,Variance,Unit');
  lines.push(
    `Net Usable Yield,${costAssumptions.baselineYieldPct.toFixed(1)},${currentResult.net_utilization_pct.toFixed(1)},+${(currentResult.net_utilization_pct - costAssumptions.baselineYieldPct).toFixed(1)},%`
  );
  lines.push(
    `Gross Foam Consumed,${baselineGrossCuFt.toFixed(2)},${grossCuFt.toFixed(2)},${(grossCuFt - baselineGrossCuFt).toFixed(2)},cu ft`
  );
  lines.push(
    `Unrecoverable Scrap,${baselineScrapCuFt.toFixed(2)},${scrapCuFt.toFixed(2)},${(scrapCuFt - baselineScrapCuFt).toFixed(2)},cu ft`
  );
  lines.push(
    `Estimated Job Cost,${baselineCost.toFixed(2)},${netEstimatedCost.toFixed(2)},${(netEstimatedCost - baselineCost).toFixed(2)},USD`
  );

  // Prefix with UTF-8 BOM (\uFEFF) for Excel compatibility
  const csvContent = '\uFEFF' + lines.join('\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${currentResult.job_id}_${currentResult.algorithm_id}_export_${isoNow.slice(0, 10)}.csv`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
